// Renders the app icon and the menu bar template icon from the logo's geometry, so the
// artwork has no build-time image dependencies. Run with: node scripts/gen-icons.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { deflateSync } from "node:zlib";

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(buf) {
  let c = 0xffffffff;
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

function png(size, pixel) {
  const raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0;
    for (let x = 0; x < size; x++) {
      const [r, g, b, a] = pixel(x + 0.5, y + 0.5);
      const o = y * (size * 4 + 1) + 1 + x * 4;
      raw[o] = r;
      raw[o + 1] = g;
      raw[o + 2] = b;
      raw[o + 3] = a;
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

function roundedRect(px, py, cx, cy, hw, hh, r) {
  const qx = Math.abs(px - cx) - hw + r;
  const qy = Math.abs(py - cy) - hh + r;
  return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r;
}

// Core: four rounded quadrants, a narrow cross and square central counter.
function core(px, py, cx, cy, half) {
  const x = Math.abs(px - cx);
  const y = Math.abs(py - cy);
  return Math.max(
    roundedRect(px, py, cx, cy, half, half, half * 0.43),
    half * 0.043 - x,
    half * 0.043 - y,
    half * 0.275 - Math.max(x, y),
  );
}

const cover = (sdf) => Math.max(0, Math.min(1, 0.5 - sdf));

// App icon: 1024 canvas, 824 body per the macOS icon grid.
const SIZE = 1024;
const body = 824;
const icon = png(SIZE, (x, y) => {
  const c = SIZE / 2;
  const shape = cover(roundedRect(x, y, c, c + 6, body / 2, body / 2, 186));
  const shadow = Math.max(0, Math.min(1, (1 - roundedRect(x, y, c, c + 22, body / 2, body / 2, 186) / 40))) * 0.35;
  const line = cover(core(x, y, c, c + 6, 242));
  const t = (y - (c - body / 2)) / body;
  const base = Math.round(34 - 26 * Math.max(0, Math.min(1, t)));
  const rim = cover(Math.abs(roundedRect(x, y, c, c + 6, body / 2 - 1.5, body / 2 - 1.5, 185)) - 1.5) * 0.08;
  const v = base + (255 - base) * Math.min(1, line + rim);
  const alpha = Math.max(shape, shadow * (1 - shape));
  const lum = shape > 0 ? v : 0;
  return [lum, lum, lum, Math.round(alpha * 255)];
});

// Menu bar template icon: 36px (18pt @2x), black on transparent.
const TRAY = 36;
const tray = png(TRAY, (x, y) => {
  const line = cover(core(x, y, TRAY / 2, TRAY / 2, 15));
  return [0, 0, 0, Math.round(line * 255)];
});

mkdirSync("assets", { recursive: true });
writeFileSync("assets/icon.png", icon);
writeFileSync(
  "src/shell/tray-icon.ts",
  `// Generated by scripts/gen-icons.mjs.\nexport const TRAY_ICON_PNG = "${tray.toString("base64")}";\n`,
);
console.log("wrote assets/icon.png and src/shell/tray-icon.ts");
